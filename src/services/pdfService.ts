/**
 * Export a saved page as a PDF and open the share sheet.
 *
 * expo-print renders HTML into a PDF in the app's cache folder; expo-sharing
 * hands that file to WhatsApp, email, Drive, a printer, etc. Creating the PDF
 * works offline; sending it obviously needs whatever the chosen app needs.
 */
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { Platform } from 'react-native';
import { escapeHtml, pageLabel } from '../utils/pageHelpers';
import { formatDate, formatTimestamp, toTimestamp } from '../utils/dates';
import { formatCoords } from './locationService';
import { photoAsDataUri } from './photoService';
import type { Amendment, Officer, Page, Photo } from '../types';

export interface PageDetails {
  page: Page;
  photos: Photo[];
  amendments: Amendment[];
  officer: Officer;
}

const row = (label: string, value: string | null | undefined) =>
  `<tr><th>${escapeHtml(label)}</th><td>${escapeHtml(value || '—')}</td></tr>`;

export async function buildPageHtml({ page, photos, amendments, officer }: PageDetails): Promise<string> {
  // iOS cannot load local file:// images while printing, so inline them as base64.
  const dataUris = (await Promise.all(photos.map((p) => photoAsDataUri(p.uri)))).filter(Boolean);

  return `<!doctype html><html><head><meta charset="utf-8"/>
  <style>
    body { font-family: -apple-system, Roboto, Arial, sans-serif; color: #111; padding: 24px; }
    h1 { font-size: 20px; margin: 0 0 4px; } .sub { color: #555; margin: 0 0 16px; }
    table { width: 100%; border-collapse: collapse; margin-bottom: 16px; }
    th { text-align: left; width: 30%; vertical-align: top; padding: 6px; background: #f4f4f5; }
    td { padding: 6px; border-bottom: 1px solid #ddd; }
    .photos img { width: 48%; margin: 1%; border: 1px solid #ccc; }
    .amend { border-left: 4px solid #b7791f; padding: 6px 10px; margin: 8px 0; background: #fffaf0; }
    footer { margin-top: 24px; font-size: 11px; color: #666; }
  </style></head><body>
    <h1>CopNote — ${escapeHtml(pageLabel(page))}: ${escapeHtml(page.title)}</h1>
    <p class="sub">${escapeHtml(`${officer.rank} ${officer.fullName}`)} · Reg. no. ${escapeHtml(officer.regimentalNumber)} · ${escapeHtml(officer.station)}</p>
    <table>
      ${row('Serial number', page.serialNumber)}
      ${row('Incident date', `${formatDate(page.incidentDate)} ${page.incidentTime}`)}
      ${row('Location', page.location)}
      ${row('GPS', formatCoords(page.latitude, page.longitude))}
      ${row('Incident type', page.incidentType)}
      ${row('People involved', page.peopleInvolved)}
      ${row('Description', page.description)}
      ${row('Action taken', page.actionTaken)}
      ${row('Page created', formatTimestamp(page.createdAt))}
      ${row('Page locked', formatTimestamp(page.savedAt))}
    </table>
    ${amendments.length ? `<h2>Amendments</h2>${amendments
      .map((a) => `<div class="amend"><b>${escapeHtml(formatTimestamp(a.createdAt))} — ${escapeHtml(a.author)}</b><br/>${escapeHtml(a.note)}</div>`)
      .join('')}` : ''}
    ${dataUris.length ? `<h2>Photos (${dataUris.length})</h2><div class="photos">${dataUris.map((src) => `<img src="${src}"/>`).join('')}</div>` : ''}
    <footer>Generated by CopNote on ${escapeHtml(formatTimestamp(toTimestamp()))} (device record — student project, not an official RPNGC document).</footer>
  </body></html>`;
}

/**
 * expo-print can only print the current window on web, so the page goes into
 * a hidden frame and the browser's print dialog does the rest ("Save as PDF"
 * is one of its printers). No allow-scripts: the page text never runs as code.
 */
const printInBrowser = (html: string) => {
  const frame = document.createElement('iframe');
  frame.setAttribute('sandbox', 'allow-same-origin allow-modals');
  frame.style.position = 'fixed';
  frame.style.width = '0';
  frame.style.height = '0';
  frame.style.border = '0';
  frame.onload = () => {
    const printWindow = frame.contentWindow;
    if (!printWindow) return;
    printWindow.addEventListener('afterprint', () => frame.remove());
    printWindow.focus();
    printWindow.print();
  };
  frame.srcdoc = html;
  document.body.appendChild(frame);
};

export async function sharePageAsPdf(details: PageDetails): Promise<void> {
  const html = await buildPageHtml(details);
  if (Platform.OS === 'web') {
    printInBrowser(html);
    return;
  }
  const { uri } = await Print.printToFileAsync({ html });
  if (!(await Sharing.isAvailableAsync())) {
    throw new Error(`Sharing is not available on this device. The PDF was saved to: ${uri}`);
  }
  await Sharing.shareAsync(uri, { UTI: '.pdf', mimeType: 'application/pdf', dialogTitle: `Share ${pageLabel(details.page)}` });
}
